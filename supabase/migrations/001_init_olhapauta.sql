-- OlhaPauta: Schema inicial para publicação editorial de IA, Tecnologia, Segurança, Negócios e Guias
-- Projeto Supabase: travyowpjigplzflvtxb

-- 1. Tabela principal de pautas
create table if not exists public.pautas (
  id uuid primary key default gen_random_uuid(),
  numero integer generated by default as identity unique,
  slug text not null unique,
  locale text not null default 'pt-BR',
  trilha text not null check (trilha in ('ia', 'tecnologia', 'seguranca', 'negocios', 'guias')),
  trilha_label text not null,
  status text not null default 'draft' check (status in ('draft', 'review', 'published', 'archived')),
  destaque boolean not null default false,

  titulo text not null,
  subtitulo text not null,
  resumo_curto text not null,
  tldr jsonb not null default '[]'::jsonb,
  conteudo jsonb not null default '[]'::jsonb,
  faqs jsonb not null default '[]'::jsonb,
  tags text[] not null default '{}',

  tempo_leitura text not null default '5 MIN',
  autor_nome text not null default 'Redação OlhaPauta',
  autor_cargo text not null default 'Mesa Editorial de IA',

  imagem_url text not null,
  imagem_alt text not null,
  imagem_credito text not null default 'Editorial OlhaPauta',

  audio_url text,
  source_urls text[] not null default '{}',

  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Índices para performance de listagem, trilhas, busca e ordenação
create index if not exists idx_pautas_status_published
  on public.pautas (status, published_at desc)
  where status = 'published';

create index if not exists idx_pautas_trilha_published
  on public.pautas (trilha, published_at desc)
  where status = 'published';

create index if not exists idx_pautas_locale
  on public.pautas (locale);

-- 2. Tabela de inscritos na newsletter
create table if not exists public.newsletter_subscribers (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  status text not null default 'active' check (status in ('active', 'unsubscribed')),
  source text not null default 'site_home',
  created_at timestamptz not null default now()
);

-- 3. Fila editorial para bots / Cockpit / MCP
create table if not exists public.editorial_queue (
  id uuid primary key default gen_random_uuid(),
  topic text not null,
  trilha text not null check (trilha in ('ia', 'tecnologia', 'seguranca', 'negocios', 'guias')),
  source_url text,
  priority integer not null default 5,
  status text not null default 'pending' check (status in ('pending', 'processing', 'drafted', 'rejected')),
  notes text,
  pauta_id uuid references public.pautas(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 4. Trigger automático para updated_at
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_pautas_updated_at on public.pautas;
create trigger trg_pautas_updated_at
  before update on public.pautas
  for each row execute function public.set_updated_at();

drop trigger if exists trg_editorial_queue_updated_at on public.editorial_queue;
create trigger trg_editorial_queue_updated_at
  before update on public.editorial_queue
  for each row execute function public.set_updated_at();

-- 5. Row Level Security (RLS)
alter table public.pautas enable row level security;
alter table public.newsletter_subscribers enable row level security;
alter table public.editorial_queue enable row level security;

-- Leitura pública apenas de pautas publicadas
drop policy if exists "Public can read published pautas" on public.pautas;
create policy "Public can read published pautas"
  on public.pautas
  for select
  using (status = 'published');

-- Qualquer visitante pode se inscrever na newsletter (sem poder ler e-mails alheios)
drop policy if exists "Public can subscribe to newsletter" on public.newsletter_subscribers;
create policy "Public can subscribe to newsletter"
  on public.newsletter_subscribers
  for insert
  with check (true);
